/// Dou'a à réciter après l'adhan.
///
/// Source : Sahih al-Bukhari n° 614 (d'après Jâbir ibn ʿAbdillah) :
/// « Celui qui dit, en entendant l'appel : … mérite mon intercession le
/// Jour de la Résurrection. »
class AdhanDua {
  const AdhanDua._();

  static const String arabic =
      'اللَّهُمَّ رَبَّ هَذِهِ الدَّعْوَةِ التَّامَّةِ، وَالصَّلَاةِ الْقَائِمَةِ، '
      'آتِ مُحَمَّدًا الْوَسِيلَةَ وَالْفَضِيلَةَ، '
      'وَابْعَثْهُ مَقَامًا مَحْمُودًا الَّذِي وَعَدْتَهُ';

  static const String transliteration =
      'Allâhumma rabba hâdhihi-d-daʿwati-t-tâmmah, wa-ṣ-ṣalâti-l-qâ’imah, '
      'âti Muḥammadan al-wasîlata wa-l-faḍîlah, '
      'wa-bʿath-hu maqâman maḥmûdan-il-ladhî waʿadtah.';

  static const String translation =
      'Ô Allah, Seigneur de cet appel parfait et de cette prière qui va être '
      'accomplie, accorde à Muhammad al-Wasîla et le mérite, et ressuscite-le '
      'au rang digne de louanges que Tu lui as promis.';

  static const String source = 'Sahih al-Bukhari, n° 614';

  /// Sunna pendant l'appel (Sahih Muslim n° 384 et 385).
  static const String duringAdhan =
      'Pendant l’appel, répétez les paroles du muezzin. À « Hayya ʿalâ-ṣ-ṣalâh » '
      'et « Hayya ʿalâ-l-falâh », dites : « Lâ ḥawla wa lâ quwwata illâ billâh ». '
      'Puis priez sur le Prophète ﷺ et récitez cette dou’a.';
}
